#!/usr/bin/env node
// Keeps Claude Code's subagent list in step with the agent roster.
//
// `docs/agents/<name>.md` is the one source of truth for an agent (CONFIGS +
// SCOPE AND RULES). Claude Code only lists subagents it finds in
// `.claude/agents/`, so this script writes a thin, generated pointer file there
// for every roster agent whose Status is ON. The pointer carries just `name`
// and `description` and tells the subagent to read its roster file — no rules
// are copied, so nothing can drift.
//
// Usage:
//   node scripts/agents-sync.mjs [--dir <path>]            write / update / remove mirrors
//   node scripts/agents-sync.mjs --check [--json] [--dir]  report drift, exit 1 if any
//
// Only files carrying the marker below are ever rewritten or removed;
// hand-written subagents in `.claude/agents/` are left alone.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const ROSTER_DIR = 'docs/agents';
export const MIRROR_DIR = '.claude/agents';
export const MARKER = 'Generated by scripts/agents-sync.mjs';

const lines = (text) => text.replace(/\r\n/g, '\n').split('\n');

/** Reads one `Key : value` field from an agent file's CONFIGS block. */
export function field(text, key) {
  const re = new RegExp(`^${key}\\s*:\\s*(.*)$`);
  for (const line of lines(text)) {
    const m = line.match(re);
    if (m) return m[1].trim();
  }
  return '';
}

/** The generated Claude Code subagent file for a roster agent. */
export function mirrorContent(name, description) {
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`, // a JSON string is valid, safely quoted YAML
    '---',
    `<!-- ${MARKER} from ${ROSTER_DIR}/${name}.md. Do not edit: change the roster file, then run \`node scripts/agents-sync.mjs\`. -->`,
    '',
    `You are the \`${name}\` agent. Your full definition is \`${ROSTER_DIR}/${name}.md\`: read it first and follow its SCOPE AND RULES.`,
    '`AGENTS.md` applies in full and wins on any conflict. Write only inside the paths listed under `Owns` in your definition, and finish with a short report: what changed, how it was verified, what is still open.',
    '',
  ].join('\n');
}

/** Roster agents (ON and OFF) as `{ name, description, status }`. */
export function readRoster(dir = '.') {
  const rosterDir = join(dir, ROSTER_DIR);
  if (!existsSync(rosterDir)) return [];
  return readdirSync(rosterDir)
    .filter((f) => f.endsWith('.md') && !f.startsWith('_'))
    .sort()
    .map((f) => {
      const text = readFileSync(join(rosterDir, f), 'utf8');
      const name = f.slice(0, -3);
      return { name, description: field(text, 'Description'), status: field(text, 'Status') };
    });
}

const generated = (path) => existsSync(path) && readFileSync(path, 'utf8').includes(MARKER);

/**
 * Compares (and, unless `check`, repairs) `.claude/agents/` against the roster.
 * Returns `{ agents, problems }`: `agents` are the names that should have a
 * mirror (Status ON); `problems` describe drift found *before* any repair.
 */
export function syncClaudeAgents(dir = '.', { check = false } = {}) {
  const mirrorDir = join(dir, MIRROR_DIR);
  const roster = readRoster(dir);
  const wanted = roster.filter((a) => a.status === 'ON' && a.description);
  const problems = [];

  for (const a of wanted) {
    const path = join(mirrorDir, `${a.name}.md`);
    const content = mirrorContent(a.name, a.description);
    if (!existsSync(path)) problems.push(`${MIRROR_DIR}/${a.name}.md is missing`);
    else if (!generated(path)) {
      problems.push(`${MIRROR_DIR}/${a.name}.md exists but was not generated here — left untouched`);
      continue;
    } else if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== content) problems.push(`${MIRROR_DIR}/${a.name}.md is out of date`);
    else continue;
    if (!check) { mkdirSync(mirrorDir, { recursive: true }); writeFileSync(path, content); }
  }

  if (existsSync(mirrorDir)) {
    const keep = new Set(wanted.map((a) => `${a.name}.md`));
    for (const f of readdirSync(mirrorDir).filter((x) => x.endsWith('.md') && !keep.has(x))) {
      const path = join(mirrorDir, f);
      if (!generated(path)) continue;
      problems.push(`${MIRROR_DIR}/${f} has no active roster agent behind it`);
      if (!check) rmSync(path);
    }
  }

  return { agents: wanted.map((a) => a.name), problems };
}

function main(argv) {
  const flags = { check: false, json: false, dir: '.' };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') flags.check = true;
    else if (argv[i] === '--json') flags.json = true;
    else if (argv[i] === '--dir') flags.dir = argv[++i] || '.';
    else { console.error(`agents-sync: unknown argument ${argv[i]}`); process.exit(1); }
  }
  const { agents, problems } = syncClaudeAgents(flags.dir, { check: flags.check });
  if (flags.json) console.log(JSON.stringify({ agents, problems }));
  else if (flags.check) {
    for (const p of problems) console.error(`FAIL: ${p}`);
    if (problems.length) console.error('run: node scripts/agents-sync.mjs');
    else console.log(`ok:   ${agents.length} Claude Code subagent${agents.length === 1 ? '' : 's'} in sync with ${ROSTER_DIR}/`);
  } else {
    for (const p of problems) console.log(`fixed: ${p}`);
    console.log(`${agents.length} Claude Code subagent${agents.length === 1 ? '' : 's'} in ${MIRROR_DIR}/ (restart or /agents to reload)`);
  }
  if (flags.check && problems.length) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
